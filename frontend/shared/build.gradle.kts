/** Writes the AppVersion object (project version, version code and the commit built from) for common code. */
abstract class GenerateAppVersion : DefaultTask() {
    @get:Input abstract val versionName: Property<String>
    @get:Input abstract val versionCode: Property<Int>
    @get:Input abstract val commit: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDir.file("com/foodtracker/app/AppVersion.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :shared:generateAppVersion from version.properties. Don't edit.
            |package com.foodtracker.app
            |
            |/** The project version this build was made from. */
            |object AppVersion {
            |    /** MAJOR.MINOR.PATCH, as in version.properties. */
            |    const val NAME: String = "${versionName.get()}"
            |    /** The Android version code, MAJOR * 10000 + MINOR * 100 + PATCH. */
            |    const val CODE: Int = ${versionCode.get()}
            |    /** Short git commit of the build, or "unknown" when git wasn't available. */
            |    const val COMMIT: String = "${commit.get()}"
            |}
            |""".trimMargin(),
        )
    }
}

val gitCommit: Provider<String> = providers.provider {
    try {
        providers.exec {
            commandLine("git", "rev-parse", "--short", "HEAD")
            isIgnoreExitValue = true
        }.standardOutput.asText.get().trim().ifEmpty { "unknown" }
    } catch (e: Exception) {
        "unknown"
    }
}

val generateAppVersion = tasks.register<GenerateAppVersion>("generateAppVersion") {
    versionName.set(rootProject.extra["appVersionName"] as String)
    versionCode.set(rootProject.extra["appVersionCode"] as Int)
    commit.set(gitCommit)
    outputDir.set(layout.buildDirectory.dir("generated/appVersion/commonMain/kotlin"))
}

